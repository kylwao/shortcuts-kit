#!/usr/bin/env bash
# Install shortcuts-kit from this checkout:
#   1. a `shortcuts-src` launcher that runs src/ directly (git pull = upgrade)
#   2. symlinks of skills/apple-shortcuts into each AI tool's skills directory
#
# Usage: scripts/install.sh [--no-cli] [--no-skill] [--uninstall]
# Env:   SHORTCUTS_KIT_BIN     launcher directory (default: ~/.local/bin)
#        SHORTCUTS_KIT_PYTHON  python interpreter (default: python3, needs >= 3.7)
set -euo pipefail

KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
SKILL_NAME="apple-shortcuts"
SKILL_SRC="$KIT/skills/$SKILL_NAME"
BIN_DIR="${SHORTCUTS_KIT_BIN:-$HOME/.local/bin}"
PYTHON="${SHORTCUTS_KIT_PYTHON:-python3}"

# "<tool home>:<skills dir>" — a tool is only wired up if its home exists.
SKILL_TARGETS=(
  "$HOME/.cursor:$HOME/.cursor/skills"
  "$HOME/.claude:$HOME/.claude/skills"
  "$HOME/.workbuddy:$HOME/.workbuddy/skills"
)

do_cli=1
do_skill=1
uninstall=0
for arg in "$@"; do
  case "$arg" in
    --no-cli) do_cli=0 ;;
    --no-skill) do_skill=0 ;;
    --uninstall) uninstall=1 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

install_cli() {
  if ! command -v "$PYTHON" >/dev/null 2>&1; then
    echo "error: $PYTHON not found; set SHORTCUTS_KIT_PYTHON" >&2
    exit 1
  fi
  if ! "$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 7) else 1)'; then
    echo "error: $PYTHON is older than 3.7" >&2
    exit 1
  fi
  local py
  py="$(command -v "$PYTHON")"
  mkdir -p "$BIN_DIR"
  cat > "$BIN_DIR/shortcuts-src" <<EOF
#!/usr/bin/env bash
# Generated by $KIT/scripts/install.sh
PYTHONPATH="$KIT/src\${PYTHONPATH:+:\$PYTHONPATH}" exec "$py" -m shortcuts_src.cli "\$@"
EOF
  chmod +x "$BIN_DIR/shortcuts-src"
  echo "cli:   $BIN_DIR/shortcuts-src -> $KIT/src ($("$BIN_DIR/shortcuts-src" --version))"
  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "       note: $BIN_DIR is not on PATH; add: export PATH=\"$BIN_DIR:\$PATH\"" ;;
  esac
}

install_skill() {
  local linked=0 entry home dir dest
  for entry in "${SKILL_TARGETS[@]}"; do
    home="${entry%%:*}"
    dir="${entry#*:}"
    [ -d "$home" ] || continue
    dest="$dir/$SKILL_NAME"
    mkdir -p "$dir"
    if [ -e "$dest" ] && [ ! -L "$dest" ]; then
      echo "skill: skip $dest (exists and is not a symlink)" >&2
      continue
    fi
    ln -sfn "$SKILL_SRC" "$dest"
    echo "skill: $dest -> $SKILL_SRC"
    linked=1
  done
  if [ "$linked" -eq 0 ]; then
    echo "skill: no supported AI tool found (~/.cursor, ~/.claude, ~/.workbuddy);"
    echo "       copy or symlink $SKILL_SRC into your tool's skills directory manually."
  fi
}

uninstall_all() {
  local entry dest
  if [ -f "$BIN_DIR/shortcuts-src" ] && grep -q "$KIT/scripts/install.sh" "$BIN_DIR/shortcuts-src"; then
    rm "$BIN_DIR/shortcuts-src" && echo "removed $BIN_DIR/shortcuts-src"
  fi
  for entry in "${SKILL_TARGETS[@]}"; do
    dest="${entry#*:}/$SKILL_NAME"
    if [ -L "$dest" ] && [ "$(readlink "$dest")" = "$SKILL_SRC" ]; then
      rm "$dest" && echo "removed $dest"
    fi
  done
}

if [ "$uninstall" -eq 1 ]; then
  uninstall_all
  exit 0
fi
[ "$do_cli" -eq 1 ] && install_cli
[ "$do_skill" -eq 1 ] && install_skill
exit 0
